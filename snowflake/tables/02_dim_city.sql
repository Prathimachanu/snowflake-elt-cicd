-- Dimension with SCD Type 2: history is kept using VALID_FROM / VALID_TO / IS_CURRENT
CREATE TABLE IF NOT EXISTS CORE.DIM_CITY (
  CITY_KEY    NUMBER AUTOINCREMENT,
  CITY        STRING,
  LATITUDE    FLOAT,
  LONGITUDE   FLOAT,
  VALID_FROM  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  VALID_TO    TIMESTAMP_NTZ,
  IS_CURRENT  BOOLEAN DEFAULT TRUE
);
